// Writes src/lib/monsoon/accounts/crm-schema.generated.ts from every src/lib/monsoon/testing/NNNN_*.sql, in order.
// Run after any change to a schema file: node scripts/monsoon/gen_setup_schema.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const dir = join(root, "src", "lib", "monsoon", "testing");
const files = readdirSync(dir).filter((f) => /^\d{4}_.*\.sql$/.test(f)).sort();
if (files.length === 0) throw new Error("no schema files found");
const read = (f) => readFileSync(join(dir, f), "utf8").replace(/\r\n/g, "\n").replace(/\n+$/, "");
const sql = files.map(read).join("\n\n") + "\n";
const latest = Number(files[files.length - 1].slice(0, 4));
const out =
  `// Generated by scripts/monsoon/gen_setup_schema.mjs from testing/${files.join(", testing/")}. Do not edit.\n` +
  `export const CRM_SCHEMA_SQL = ${JSON.stringify(sql)};\n` +
  `export const CRM_LATEST_VERSION = ${latest};\n`;
writeFileSync(join(root, "src", "lib", "monsoon", "accounts", "crm-schema.generated.ts"), out);
